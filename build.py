from pathlib import Path
root=Path(__file__).parent
shell=(root/'source'/'shell.html').read_text(encoding='utf-8')
core=(root/'source'/'core.js').read_text(encoding='utf-8')
app=(root/'source'/'app.js').read_text(encoding='utf-8')
observatory=(root/'source'/'observatory.js').read_text(encoding='utf-8')
observatory_css=(root/'source'/'observatory.css').read_text(encoding='utf-8')
immersive_css=(root/'source'/'immersive.css').read_text(encoding='utf-8')
immersive_js=(root/'source'/'immersive.js').read_text(encoding='utf-8')
starter_js=(root/'source'/'starter-ideas.js').read_text(encoding='utf-8')
starter_css=(root/'source'/'starter.css').read_text(encoding='utf-8')
uplift_core=(root/'source'/'uplift-core.js').read_text(encoding='utf-8')
uplift_ui=(root/'source'/'uplift-ui.js').read_text(encoding='utf-8')
uplift_css=(root/'source'/'uplift.css').read_text(encoding='utf-8')
shell=shell.replace('<!-- STARTER CSS -->','<style>\n'+starter_css+'\n</style>').replace('<script>/* STARTER IDEAS */</script>','<script>\n'+starter_js+'\n</script>')
shell=shell.replace('<!-- UPLIFT CSS -->','<style>\n'+uplift_css+'\n</style>')
shell=shell.replace('<script>/* UPLIFT CORE */</script>','<script>\n'+uplift_core+'\n</script>').replace('<script>/* UPLIFT UI */</script>','<script>\n'+uplift_ui+'\n</script>')
shell=shell.replace('<!-- IMMERSIVE CSS -->','<style>\n'+immersive_css+'\n</style>').replace('<script>/* IMMERSIVE */</script>','<script>\n'+immersive_js+'\n</script>')
shell=shell.replace('<!-- OBSERVATORY CSS -->','<style>\n'+observatory_css+'\n</style>').replace('<script>/* CORE */</script>','<script>\n'+core+'\n</script>').replace('<script>/* OBSERVATORY */</script>','<script>\n'+observatory+'\n</script>').replace('<script>/* APP */</script>','<script>\n'+app+'\n</script>')
(root/'index.html').write_text(shell,encoding='utf-8')
print('Built',root/'index.html', len(shell.encode('utf-8')),'bytes')
